# 5) Tokenización y sustitución preservando mayúsculas.
# ---------------------------------------------------------------------------
# Divide el texto en palabras y "no-palabras" (espacios, puntuación).
_TOKEN_RE = re.compile(r"([A-Za-z][A-Za-z'-]*|\s+|[^A-Za-z\s])")


def _preserve_case(original: str, translation: str) -> str:
    """Adapta la capitalización de la traducción a la del original."""
    if not translation:
        return translation
    if original.isupper() and len(original) > 1:
        return translation.upper()
    if original[0].isupper():
        return translation[0].upper() + translation[1:]
    return translation


def _lookup(word: str) -> str | None:
    """Busca la traducción de una palabra en PROPER_NOUNS, KEYS y WORD_DICT."""
    lower = word.lower()
    if lower in PROPER_NOUNS:
        return None
    if lower in KEYS:
        return KEYS[lower]
    if lower in WORD_DICT:
        return WORD_DICT[lower]
    return None


def translate_words(text: str) -> str:
    """Sustituye cada palabra suelta por su traducción preservando capitalización."""
    out = []
    for token in _TOKEN_RE.findall(text):
        if not token or not token[0].isalpha():
            out.append(token)
            continue
        tr = _lookup(token)
        if tr is not None:
            out.append(_preserve_case(token, tr))
        else:
            out.append(token)
    return "".join(out)


