# 6) Bucle principal.
# ---------------------------------------------------------------------------
def main() -> None:
    po = polib.pofile(PO_FILE)
    modified = 0
    total = 0
    by_type = {
        "keys": 0,
        "citations": 0,
        "descriptions": 0,
        "dialogue": 0,
        "parenthetical": 0,
        "other": 0,
    }

    for entry in po:
        is_db = any(ref[0] == "dat/data.base" for ref in entry.occurrences)
        if not is_db or entry.msgstr:
            continue

        total += 1
        msgid = entry.msgid
        translated = None

        # --- 1) Citas literarias (pueden ser multi-línea) ---
        if msgid.startswith("["):
            translated = translate_citation(msgid)
            by_type["citations"] += 1

        # --- 2) Claves cortas (con o sin espacios, <30 chars) ---
        if translated is None and len(msgid) < 30:
            prefix = ""
            core = msgid.strip()
            # Quitar prefijos *, ~
            while core[:1] in ("*", "~"):
                prefix += core[:1]
                core = core[1:].lstrip()
            # Quitar sufijos *, ~
            suffix = ""
            while core[-1:] in ("*", "~"):
                suffix = core[-1:] + suffix
                core = core[:-1].rstrip()
            key = core.lower()
            if key in KEYS:
                translated = f"{prefix}{KEYS[key]}{suffix}"
                by_type["keys"] += 1
            elif msgid.strip().lower() in KEYS:
                translated = KEYS[msgid.strip().lower()]
                by_type["keys"] += 1

        # --- 3) Diálogos (entrecomillados): se intentan traducir
        #       sustituyendo palabras sueltas; si no, se dejan. ---
        if translated is None and (msgid.startswith('"') or msgid.startswith("'")):
            candidate = translate_words(msgid)
            if candidate != msgid:
                translated = candidate
                by_type["dialogue"] += 1

        # --- 4) Paréntesis sueltos: igual que diálogo ---
        if translated is None and msgid.startswith("("):
            candidate = translate_words(msgid)
            if candidate != msgid:
                translated = candidate
                by_type["parenthetical"] += 1

        # --- 5) Descripciones largas: sustitución palabra-por-palabra ---
        if translated is None:
            candidate = translate_words(msgid)
            if candidate != msgid:
                translated = candidate
                by_type["descriptions"] += 1

        if translated:
            entry.msgstr = translated
            modified += 1

    po.save(PO_FILE)

    print(f"Total entradas dat/data.base sin traducir: {total}")
    print(f"Traducidas en esta pasada: {modified}")
    print(
        f"  claves={by_type['keys']}, citas={by_type['citations']}, "
        f"descripciones={by_type['descriptions']}, "
        f"diálogos={by_type['dialogue']}, paréntesis={by_type['parenthetical']}"
    )
    print(f"Sin traducir: {total - modified}")


if __name__ == "__main__":
    main()
