# ---------------------------------------------------------------------------
# 1) Citas literarias: estructura "[ ..., by Author, ... ]"
# ---------------------------------------------------------------------------
CITATION_REPL = [
    (re.compile(r"\btranslated by\b"), "traducida por"),
    (re.compile(r"\bas translated\b"), "traducida como"),
    (re.compile(r"\bdirected by\b"), "dirigida por"),
    (re.compile(r"\bscreenplay by\b"), "guion de"),
    (re.compile(r"\badapted by\b"), "adaptada por"),
    (re.compile(r"\bnarrated by\b"), "narrada por"),
    (re.compile(r"\bedited by\b"), "editada por"),
    (re.compile(r"\bcompiled by\b"), "compilada por"),
    (re.compile(r"\billustrated by\b"), "ilustrada por"),
    (re.compile(r"\bintroduction by\b"), "introducción de"),
    (re.compile(r"\bforeword by\b"), "prólogo de"),
    (re.compile(r"\bafterword by\b"), "epílogo de"),
    (re.compile(r",\s*from\s+"), ", de "),
    (re.compile(r",\s*in\s+(?=[A-Z])"), ", en "),
    (re.compile(r"\bby\b"), "por"),
    (re.compile(r"\band\b"), "y"),
]


def translate_citation(text: str) -> str:
    """Traduce la estructura de una cita conservando el contenido entre corchetes."""
    m = re.match(r"^(\[\s*)(.*?)(\s*\])$", text)
    if not m:
        return text
    prefix, inner, suffix = m.group(1), m.group(2), m.group(3)
    for pat, repl in CITATION_REPL:
        inner = pat.sub(repl, inner)
    return f"{prefix}{inner}{suffix}"


