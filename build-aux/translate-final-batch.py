def build_symbols_dict(po):
    """Construye el diccionario de traducciones para dat/symbols.

    Para los S_xxx y G_xxx (mapeos tecnicos) la traduccion es el
    mismo msgid (los identificadores no se traducen). Para los
    comentarios "# ..." despues de un tabulador, se intenta traducir
    la parte descriptiva. Para las lineas de tipo start:/Description:/
    Handling:/etc., se usan las traducciones manuales.
    """
    result = {}
    for entry in po:
        if not any(ref[0] == "dat/symbols" for ref in entry.occurrences):
            continue
        if entry.msgid in SYMBOLS_DESCRIPTIONS:
            result[entry.msgid] = SYMBOLS_DESCRIPTIONS[entry.msgid]
            continue
        # Lineas S_xxx: 'mapeo tecnico, dejar igual
        # pero intentar traducir el comentario final
        msgid = entry.msgid
        if "\t# " in msgid:
            prefix, comment = msgid.split("\t# ", 1)
            translated = comment
            for eng, esp in SYMBOLS_COMMENT_TRANSLATIONS.items():
                translated = translated.replace(eng, esp)
            if translated != comment:
                # Conservamos los espacios/tabuladores originales
                result[msgid] = prefix + "\t# " + translated
            else:
                result[msgid] = msgid
        else:
            # Sin comentario traducible: mismo valor (no se traduce)
            result[msgid] = msgid
    return result


def main():
    po = polib.pofile(PO_FILE)

    # Construir diccionario completo
    symbols_dict = build_symbols_dict(po)
    translations = {}
    translations.update(symbols_dict)
    translations.update(OPTHELP)
    translations.update(HISTORY)
    translations.update(DATABASE)

    # Estadisticas
    per_file = {f: {"total": 0, "translated": 0} for f in TARGETS}
    untranslated = {f: [] for f in TARGETS}

    for entry in po:
        target = None
        for ref in entry.occurrences:
            if ref[0] in TARGETS:
                target = ref[0]
                break
        if target is None:
            continue
        per_file[target]["total"] += 1
        # Solo aplicar traduccion a entradas vacias (no sobrescribir las ya traducidas)
        if entry.msgstr:
            per_file[target]["translated"] += 1
            continue
        if entry.msgid in translations and translations[entry.msgid]:
            entry.msgstr = translations[entry.msgid]
            per_file[target]["translated"] += 1
        else:
            untranslated[target].append((int(entry.occurrences[0][1]), entry.msgid))

    po.save(PO_FILE)

    # Imprimir estadisticas
    print("=" * 60)
    print("Estadisticas de traduccion")
    print("=" * 60)
    total_all = 0
    translated_all = 0
    for f in TARGETS:
        t = per_file[f]["total"]
        tr = per_file[f]["translated"]
        total_all += t
        translated_all += tr
        print(f"  {f:20s}  {tr:4d} / {t:4d}  ({100 * tr / t if t else 0:5.1f}%)")
    print("-" * 60)
    print(
        f"  {'TOTAL':20s}  {translated_all:4d} / {total_all:4d}  "
        f"({100 * translated_all / total_all if total_all else 0:5.1f}%)"
    )
    print("=" * 60)

    # Mostrar entradas sin traducir (si quedan)
    remaining = sum(len(v) for v in untranslated.values())
    if remaining:
        print(f"\nQuedan {remaining} entradas sin traducir:")
        for f in TARGETS:
            if untranslated[f]:
                print(f"\n  --- {f} ({len(untranslated[f])}) ---")
                for ln, msgid in untranslated[f]:
                    snippet = msgid.replace("\n", "\\n")[:100]
                    print(f"    [{ln}] {snippet}")


if __name__ == "__main__":
    main()
