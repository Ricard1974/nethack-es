# 5) FUNCIÓN PRINCIPAL
# =======================================================================


def main():
    po = polib.pofile(PO_FILE)
    modified = 0
    total = 0
    untranslated_remaining = []

    for entry in po:
        is_c = any(ref[0].startswith("src/") for ref in entry.occurrences)
        if not is_c:
            continue
        total += 1
        if entry.msgstr:
            continue

        msgid = entry.msgid
        if not msgid:
            continue

        translation = get_simple_translation(msgid)
        if translation is not None:
            entry.msgstr = translation
            modified += 1
        else:
            untranslated_remaining.append(msgid)

    po.save(PO_FILE)

    print(f"Total de cadenas C: {total}")
    print(f"Traducidas: {modified}")
    print(f"Sin traducir: {len(untranslated_remaining)}")
    print(f"Porcentaje: {100.0 * modified / total if total else 0:.1f}%")

    if untranslated_remaining:
        print("\n--- 20 ejemplos de cadenas sin traducir ---")
        for s in untranslated_remaining[:20]:
            print(f"  {s[:120]!r}")


if __name__ == "__main__":
    main()
