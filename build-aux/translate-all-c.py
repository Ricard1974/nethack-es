# Formato "are/aren't/are being X" -> "estás X" / "no estás X" / "estás siendo X"
# Maneja patrones comunes como "are X", "aren't X", "are being X"
def translate_are(are_text, rest):
    """Convierte 'are X' / 'aren't X' a español"""
    if are_text == "are":
        return "estás " + rest
    elif are_text == "aren't":
        return "no estás " + rest
    elif are_text == "are being":
        return "estás siendo " + rest
    elif are_text == "aren't being":
        return "no estás siendo " + rest
    return None


