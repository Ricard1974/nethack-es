# Patrón: "are/aren't/isn't/haven't/doesn't/don't/cannot/can't X %s" -> conjugación
def try_conjugate_verb(s):
    """Intenta traducir conjugando un verbo en español."""
    s = s.strip()

    # Buscar prefijo verbo + resto
    for prefix, prefix_es in [
        ("aren't", "no estás"),
        ("are", "estás"),
        ("isn't", "no está"),
        ("is", "está"),
        ("wasn't", "no estabas"),
        ("was", "estabas"),
        ("haven't", "no tienes"),
        ("have", "tienes"),
        ("hasn't", "no tiene"),
        ("has", "tiene"),
        ("hadn't", "no tenías"),
        ("had", "tenías"),
        ("don't", "no"),
        ("doesn't", "no"),
        ("didn't", "no"),
        ("do", ""),
        ("does", ""),
        ("did", ""),
        ("can't", "no puedes"),
        ("can", "puedes"),
        ("couldn't", "no podías"),
        ("could", "podías"),
        ("won't", "no"),
        ("will not", "no"),
        ("will", ""),
        ("wouldn't", "no"),
        ("would", ""),
        ("shouldn't", "no deberías"),
        ("should", "deberías"),
        ("mustn't", "no debes"),
        ("must", "debes"),
        ("may not", "no puedes"),
        ("may", "puedes"),
        ("might not", "no podrías"),
        ("might", "podrías"),
    ]:
        if s == prefix:
            return prefix_es
        if s.startswith(prefix + " "):
            rest = s[len(prefix) :].lstrip()
            # Si la traducción es vacía, sólo el resto
            if not prefix_es:
                return rest
            # Si la traducción es "no", devolver "no <rest>"
            if prefix_es == "no":
                return "no " + rest
            return prefix_es + " " + rest

    return None


# =======================================================================
# 4) FUNCIONES AUXILIARES
# =======================================================================


def get_simple_translation(msgid):
    """Intenta obtener una traducción simple."""
    # 1. Buscar en diccionario directo
    if msgid in DIRECT:
        return DIRECT[msgid]

    # 2. Intentar conjugación de verbos simples
    conjugated = try_conjugate_verb(msgid)
    if conjugated is not None:
        return conjugated

    return None


